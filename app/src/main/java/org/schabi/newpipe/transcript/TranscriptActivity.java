package org.schabi.newpipe.transcript;

import android.os.Bundle;
import android.view.View;
import android.widget.Button;
import android.widget.LinearLayout;
import android.widget.ScrollView;
import android.widget.TextView;

import androidx.annotation.Nullable;
import androidx.appcompat.app.AppCompatActivity;

import org.schabi.newpipe.DownloaderImpl;
import org.schabi.newpipe.R;
import org.schabi.newpipe.extractor.MediaFormat;
import org.schabi.newpipe.extractor.stream.SubtitlesStream;
import org.schabi.newpipe.player.helper.PlayerHelper;
import org.schabi.newpipe.util.ExtractorHelper;
import org.schabi.newpipe.util.ThemeHelper;
import org.schabi.newpipe.util.external_communication.ShareUtils;

import java.util.List;

import io.reactivex.rxjava3.android.schedulers.AndroidSchedulers;
import io.reactivex.rxjava3.core.Single;
import io.reactivex.rxjava3.disposables.CompositeDisposable;
import io.reactivex.rxjava3.schedulers.Schedulers;

import static org.schabi.newpipe.extractor.stream.DeliveryMethod.PROGRESSIVE_HTTP;

/** Displays and shares a transcript for a video received from another app. */
public class TranscriptActivity extends AppCompatActivity {
    public static final String EXTRA_SERVICE_ID = "service_id";
    public static final String EXTRA_URL = "url";
    private static final String STATE_TRACK_URL = "track_url";
    private static final String STATE_FORMAT = "track_format";
    private static final String STATE_TITLE = "video_title";
    private static final String STATE_AUTO = "track_auto";

    private final CompositeDisposable disposables = new CompositeDisposable();
    private LinearLayout content;
    private TextView status;
    private Button shareButton;
    private Button changeButton;
    private Button retryButton;
    private String trackUrl;
    private String trackFormat;
    private boolean autoGenerated;
    private String videoTitle = "";
    private String transcript;

    @Override
    protected void onCreate(@Nullable final Bundle savedInstanceState) {
        ThemeHelper.setTheme(this);
        super.onCreate(savedInstanceState);
        setTitle(R.string.show_transcript);
        if (savedInstanceState != null) {
            trackUrl = savedInstanceState.getString(STATE_TRACK_URL);
            trackFormat = savedInstanceState.getString(STATE_FORMAT);
            autoGenerated = savedInstanceState.getBoolean(STATE_AUTO);
            videoTitle = savedInstanceState.getString(STATE_TITLE, "");
        }
        createView();
        if (trackUrl == null || trackFormat == null) {
            loadTracks();
        } else {
            loadTranscript();
        }
    }

    private void createView() {
        final int padding = (int) (16 * getResources().getDisplayMetrics().density);
        final LinearLayout root = new LinearLayout(this);
        root.setOrientation(LinearLayout.VERTICAL);
        root.setPadding(padding, padding, padding, padding);
        status = new TextView(this);
        root.addView(status);
        final ScrollView scroll = new ScrollView(this);
        content = new LinearLayout(this);
        content.setOrientation(LinearLayout.VERTICAL);
        scroll.addView(content);
        root.addView(scroll, new LinearLayout.LayoutParams(
                LinearLayout.LayoutParams.MATCH_PARENT, 0, 1));
        shareButton = new Button(this);
        shareButton.setText(R.string.share);
        shareButton.setOnClickListener(v -> ShareUtils.shareText(this, videoTitle, transcript));
        root.addView(shareButton);
        changeButton = new Button(this);
        changeButton.setText(R.string.transcript_change_track);
        changeButton.setOnClickListener(v -> {
            trackUrl = null;
            trackFormat = null;
            loadTracks();
        });
        root.addView(changeButton);
        retryButton = new Button(this);
        retryButton.setText(R.string.transcript_retry);
        retryButton.setOnClickListener(v -> {
            if (trackUrl == null) {
                loadTracks();
            } else {
                loadTranscript();
            }
        });
        root.addView(retryButton);
        setContentView(root);
    }

    private void showLoading() {
        content.removeAllViews();
        status.setText(R.string.transcript_loading);
        shareButton.setVisibility(View.GONE);
        changeButton.setVisibility(View.GONE);
        retryButton.setVisibility(View.GONE);
    }

    private void loadTracks() {
        showLoading();
        final int serviceId = getIntent().getIntExtra(EXTRA_SERVICE_ID, -1);
        final String url = getIntent().getStringExtra(EXTRA_URL);
        disposables.add(ExtractorHelper.getStreamInfo(serviceId, url, false)
                .subscribeOn(Schedulers.io())
                .observeOn(AndroidSchedulers.mainThread())
                .subscribe(info -> {
                    videoTitle = info.getName();
                    showTracks(info.getSubtitles());
                }, error -> showError()));
    }

    private void showTracks(@Nullable final List<SubtitlesStream> tracks) {
        content.removeAllViews();
        int count = 0;
        if (tracks != null) {
            for (final SubtitlesStream track : tracks) {
                final MediaFormat format = track.getFormat();
                if (!track.isUrl() || track.getDeliveryMethod() != PROGRESSIVE_HTTP
                        || (format != MediaFormat.SRT && format != MediaFormat.VTT
                        && format != MediaFormat.TTML)) {
                    continue;
                }
                final Button button = new Button(this);
                button.setText(PlayerHelper.captionLanguageOf(this, track));
                button.setOnClickListener(v -> {
                    trackUrl = track.getContent();
                    trackFormat = format.getSuffix();
                    autoGenerated = track.isAutoGenerated();
                    loadTranscript();
                });
                content.addView(button);
                count++;
            }
        }
        status.setText(count == 0 ? R.string.transcript_no_subtitles
                : R.string.transcript_choose_track);
    }

    private void loadTranscript() {
        showLoading();
        final String url = trackUrl;
        final String format = trackFormat;
        disposables.add(Single.fromCallable(() -> TranscriptParser.parse(format,
                        DownloaderImpl.getInstance().get(url).ensureSuccessResponseCode()
                                .responseBody(), autoGenerated))
                .subscribeOn(Schedulers.io())
                .observeOn(AndroidSchedulers.mainThread())
                .subscribe(result -> {
                    transcript = result;
                    status.setText("");
                    final TextView text = new TextView(this);
                    text.setTextIsSelectable(true);
                    text.setText(result);
                    content.addView(text);
                    shareButton.setVisibility(View.VISIBLE);
                    changeButton.setVisibility(View.VISIBLE);
                }, error -> showError()));
    }

    private void showError() {
        status.setText(R.string.transcript_error);
        retryButton.setVisibility(View.VISIBLE);
        changeButton.setVisibility(trackUrl == null ? View.GONE : View.VISIBLE);
    }

    @Override
    protected void onSaveInstanceState(final Bundle outState) {
        outState.putString(STATE_TRACK_URL, trackUrl);
        outState.putString(STATE_FORMAT, trackFormat);
        outState.putBoolean(STATE_AUTO, autoGenerated);
        outState.putString(STATE_TITLE, videoTitle);
        super.onSaveInstanceState(outState);
    }

    @Override
    protected void onDestroy() {
        disposables.clear();
        super.onDestroy();
    }
}
