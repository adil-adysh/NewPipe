package org.schabi.newpipe.transcript;

import org.jsoup.Jsoup;
import org.jsoup.nodes.Element;
import org.jsoup.nodes.Node;
import org.jsoup.nodes.TextNode;
import org.jsoup.parser.Parser;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/** Converts subtitle cues to readable transcript text. */
public final class TranscriptParser {
    private TranscriptParser() { }

    public static String parse(final String format, final String source) {
        return parse(format, source, false);
    }

    public static String parse(final String format, final String source,
                               final boolean autoGenerated) {
        final List<String> cues = new ArrayList<>();
        if ("ttml".equals(format.toLowerCase(Locale.ROOT))) {
            final Element root = Jsoup.parse(source, "", Parser.xmlParser());
            for (final Element paragraph : root.select("p")) {
                final StringBuilder text = new StringBuilder();
                appendXmlText(paragraph, text);
                addCue(cues, text.toString(), autoGenerated);
            }
        } else if ("srt".equalsIgnoreCase(format) || "vtt".equalsIgnoreCase(format)) {
            final String normalized = source.replace("\r\n", "\n").replace('\r', '\n');
            for (final String block : normalized.split("\\n\\s*\\n")) {
                final String[] lines = block.split("\n");
                int timing = -1;
                for (int i = 0; i < lines.length; i++) {
                    if (lines[i].contains("-->")) {
                        timing = i;
                        break;
                    }
                }
                if (timing < 0) {
                    continue;
                }
                final StringBuilder text = new StringBuilder();
                for (int i = timing + 1; i < lines.length; i++) {
                    if (text.length() > 0) {
                        text.append('\n');
                    }
                    text.append(Jsoup.parse(lines[i].replaceAll(
                            "<\\d{2}:\\d{2}(?::\\d{2})?\\.\\d{3}>", "")).text());
                }
                addCue(cues, text.toString(), autoGenerated);
            }
        } else {
            throw new IllegalArgumentException("Unsupported subtitle format");
        }
        if (cues.isEmpty()) {
            throw new IllegalArgumentException("No subtitle text");
        }
        return String.join("\n", cues);
    }

    private static void appendXmlText(final Node node, final StringBuilder text) {
        if (node instanceof TextNode) {
            text.append(((TextNode) node).getWholeText());
        } else if (node instanceof Element && "br".equalsIgnoreCase(((Element) node).tagName())) {
            text.append('\n');
        }
        for (final Node child : node.childNodes()) {
            appendXmlText(child, text);
        }
    }

    private static void addCue(final List<String> cues, final String rawText,
                               final boolean autoGenerated) {
        final String text = rawText.replace('\u00a0', ' ').trim();
        if (text.isEmpty()) {
            return;
        }
        if (autoGenerated && !cues.isEmpty()) {
            final int last = cues.size() - 1;
            final String previous = cues.get(last);
            final int maxOverlap = Math.min(previous.length(), text.length());
            for (int length = maxOverlap; length > 0; length--) {
                final int start = previous.length() - length;
                if ((start == 0 || Character.isWhitespace(previous.charAt(start - 1)))
                        && (length == text.length()
                        || Character.isWhitespace(text.charAt(length)))
                        && previous.regionMatches(start, text, 0, length)) {
                    cues.set(last, previous + text.substring(length));
                    return;
                }
            }
        }
        cues.add(text);
    }
}
